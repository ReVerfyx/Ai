#!/usr/bin/env python3
"""Generate a small original Russian warm-up corpus for fast language sanity checks.

This corpus is intentionally simple and synthetic. Its job is to teach the
from-scratch character/Unicode model basic Russian spelling, punctuation,
dialogue turns and short factual answer patterns before broad web training.
"""
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data" / "warmup" / "ru-basic.txt"
OUT.parent.mkdir(parents=True, exist_ok=True)

subjects = [
    ("небо", "голубое"), ("трава", "зелёная"), ("снег", "белый"),
    ("вода", "жидкая"), ("огонь", "горячий"), ("лёд", "холодный"),
    ("кошка", "животное"), ("собака", "животное"), ("Москва", "город"),
    ("Python", "язык программирования"), ("Linux", "операционная система"),
    ("Интернет", "сеть"), ("компьютер", "устройство"), ("человек", "живое существо"),
]

qa = [
    ("Привет!", "Привет! Чем могу помочь?"),
    ("Кто ты?", "Я ReVerfyx AI."),
    ("Как тебя зовут?", "Меня зовут ReVerfyx AI."),
    ("Что ты умеешь?", "Я учусь отвечать на вопросы и работать с текстом."),
    ("Что такое нейросеть?", "Нейросеть — это модель, которая учится на данных."),
    ("Что такое программа?", "Программа — это набор инструкций для компьютера."),
    ("Что такое алгоритм?", "Алгоритм — это последовательность действий для решения задачи."),
    ("Что такое файл?", "Файл — это данные, сохранённые на носителе."),
    ("Что такое сервер?", "Сервер — это компьютер или программа, которая обслуживает запросы."),
    ("Что такое база данных?", "База данных хранит и организует информацию."),
    ("Сколько будет два плюс два?", "Два плюс два равно четыре."),
    ("Сколько будет три плюс три?", "Три плюс три равно шесть."),
    ("Напиши короткий ответ.", "Хорошо."),
    ("Ты понимаешь русский язык?", "Я учусь понимать русский язык."),
    ("Ответь по-русски.", "Хорошо, отвечаю по-русски."),
]

lines = []
for _ in range(220):
    for q, a in qa:
        lines.append(f"user: {q}\nassistant: {a}")
    for noun, desc in subjects:
        lines.append(f"user: Что такое {noun}?\nassistant: {noun} — это {desc}.")
        lines.append(f"{noun}. {noun}. {desc}.")
        lines.append(f"Слово: {noun}. Описание: {desc}.")
    lines.extend([
        "Это простое предложение на русском языке.",
        "Я читаю текст и учусь продолжать предложения.",
        "Вопрос заканчивается знаком вопроса? Ответ заканчивается точкой.",
        "Большая буква используется в начале предложения.",
        "Русский язык использует кириллицу.",
        "Программирование связано с кодом, алгоритмами и данными.",
        "Нейронная сеть обучается на примерах текста.",
        "Модель получает входные данные и создаёт выходные данные.",
        "Если я не знаю ответ, лучше сказать об этом прямо.",
        "Короткий понятный ответ лучше случайного набора символов.",
    ])

random.Random(1337).shuffle(lines)
OUT.write_text("\n\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {len(lines)} warm-up samples to {OUT}")
